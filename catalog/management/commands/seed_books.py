class Command(BaseCommand):
    help = "Наповнює базу тестовими категоріями та книгами"

    def handle(self, *args, **options):
        cats = {}
        for name in CATEGORIES:
            cat, _ = Category.objects.get_or_create(
                name=name, defaults={"slug": ukr_slugify(name)}
            )
            cats[name] = cat
        self.stdout.write(self.style.SUCCESS(f"Категорій: {len(cats)}"))

        created = 0
        for title, author, cat_name, price, btype, stock, desc in BOOKS:
            slug = ukr_slugify(f"{title}-{author}")
            _, was_created = Book.objects.get_or_create(
                slug=slug,
                defaults={
                    "title": title,
                    "author": author,
                    "category": cats[cat_name],
                    "price": price,
                    "book_type": btype,
                    "stock": stock,
                    "description": desc,
                    "available": True,
                },
            )
            created += int(was_created)
        self.stdout.write(self.style.SUCCESS(f"Створено книг: {created}"))
